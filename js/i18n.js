  var listeners = [];

  function t(key, vars) {
    var s = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) { s = s.split('{' + k + '}').join(vars[k]); });
    }
    return s;
  }

  function apply() {
    document.documentElement.lang = lang;
    var i, els = document.querySelectorAll('[data-i18n]');
    for (i = 0; i < els.length; i++) els[i].textContent = t(els[i].getAttribute('data-i18n'));
    els = document.querySelectorAll('[data-i18n-aria]');
    for (i = 0; i < els.length; i++) els[i].setAttribute('aria-label', t(els[i].getAttribute('data-i18n-aria')));
    els = document.querySelectorAll('.langbtn');
    for (i = 0; i < els.length; i++) {
      els[i].classList.toggle('on', els[i].getAttribute('data-lang') === lang);
    }
    document.title = t('title') + ' – ' + t('subtitle');
  }

  function setLang(l) {
    if (l !== 'hu' && l !== 'en') return;
    lang = l;
    try { localStorage.setItem('aso.lang', l); } catch (e) { /* ignore */ }
    apply();
    listeners.forEach(function (f) { f(l); });
  }

  function num(n) {
    try { return new Intl.NumberFormat(lang === 'hu' ? 'hu-HU' : 'en-US').format(n); }
    catch (e) { return String(n); }
  }

